import 'dart:io';

import 'package:path/path.dart' as p;

import '../config.dart';
import 'package.dart';
import 'bundle_policy.dart';

/// Fewer bundleable files than this run unbundled (one compile is no gain).
const minBundle = 2;

/// Generated entrypoint under `test/`; `discoverTests` skips this pattern.
const bundleFileName = 'flutter_test_bundle.g.dart';

/// Files sharing one compile, files that run alone (with reasons) and
/// SOFT-flagged files awaiting a policy verdict.
typedef BundlePlan = ({
  List<String> bundled,
  Map<String, List<String>> isolated,
  List<String> unreviewed,
});

/// A package's test files and their [BundlePlan].
typedef LoadedBundlePlan = ({List<String> files, BundlePlan plan});

/// Plans the tests of [packageDir] (or [files]) against the policy.
///
/// [isolationPatterns] default to `Tooling().isolationRegExps`.
///
/// A file is isolated when the policy says so, it has a HARD hazard, or it
/// has a SOFT hazard and no `bundle_safe` verdict; fewer than [minBundle]
/// bundleable files are all isolated as `bundle-too-small`. An unusable
/// policy is logged and isolates everything as `policy-error`, so it can
/// only cost time, never hide a test.
LoadedBundlePlan loadBundlePlan({
  required String packageDir,
  required String? policyPath,
  required String packageKey,
  required void Function(String message) log,
  List<String>? files,
  List<RegExp>? isolationPatterns,
}) {
  final patterns = isolationPatterns ?? Tooling().isolationRegExps;
  final tests = files ?? discoverTests(packageDir);
  var policy = const BundlePolicy();
  var broken = false;
  try {
    if (policyPath != null) policy = BundlePolicy.load(policyPath, packageKey);
  } on BundlePolicyException catch (e) {
    log('bundle policy unusable ($e); running unbundled');
    broken = true;
  }
  // Isolation reasons per file, in sorted order; empty means bundleable.
  final reasons = <String, List<String>>{};
  final unreviewed = <String>[];
  for (final file in tests.toList()..sort()) {
    if (broken) {
      reasons[file] = ['policy-error'];
      continue;
    }
    final (:hard, :soft) = _scan(packageDir, file, patterns);
    final policyReason = policy.isolate[file];
    final unverified = soft.isNotEmpty && !policy.bundleSafe.containsKey(file);
    if (unverified && policyReason == null) unreviewed.add(file);
    reasons[file] = [
      if (policyReason != null) 'policy: $policyReason',
      ...hard,
      if (unverified) ...soft,
    ];
  }
  final bundled = [
    for (final e in reasons.entries)
      if (e.value.isEmpty) e.key,
  ];
  final small = bundled.length < minBundle;
  return (
    files: tests,
    plan: (
      bundled: small ? <String>[] : bundled,
      isolated: {
        for (final e in reasons.entries)
          if (e.value.isNotEmpty || small)
            e.key: e.value.isEmpty ? ['bundle-too-small'] : e.value,
      },
      unreviewed: unreviewed,
    ),
  );
}

/// Dart source of one entrypoint that runs each file's `main()` in a
/// `group()` named after the file (how failures are attributed back).
/// Throws [ArgumentError] for a file that is not a `test/**.dart` path.
String renderBundle(List<String> files) {
  for (final file in files) {
    if (!isSafeTestPath(file) || !file.endsWith('.dart')) {
      throw ArgumentError.value(file, 'files', 'not a test file under test/');
    }
  }
  String quote(String s) =>
      "'${s.replaceAllMapped(RegExp(r"[\\'$]"), (m) => '\\${m[0]}')}'";
  return [
    '// GENERATED by test_impact (bundle test).',
    '// Do not edit or commit; deleted after each run.',
    '// ignore_for_file: directives_ordering, depend_on_referenced_packages',
    "import 'package:flutter_test/flutter_test.dart' show group;",
    '',
    for (var i = 0; i < files.length; i++)
      'import ${quote(files[i].substring(5))} as t$i;',
    '',
    'void main() {',
    for (var i = 0; i < files.length; i++)
      '  group(${quote(files[i])}, t$i.main);',
    '}',
    '',
  ].join('\n');
}

final _annotation = RegExp(
  r'^@(TestOn|Tags|Timeout|Skip|OnPlatform|Retry)\b',
  multiLine: true,
);
final _main = RegExp(
  r'^((?:void|Future<void>|FutureOr<void>|Future|dynamic)\s+)?'
  r'main\s*\(([^)]*)\)\s*(async\b)?',
  multiLine: true,
);
final _import = RegExp(
  r"""^\s*(?:import|export)\s+['"]([^'"]+)['"]""",
  multiLine: true,
);

/// `code in source` reasons: HARD ones always isolate [file], SOFT ones
/// are up to the policy. Scans the file, the relative helpers it imports
/// (transitively, inside the package) and each `flutter_test_config.dart`
/// up to the package root.
({List<String> hard, List<String> soft}) _scan(
  String packageDir,
  String file,
  List<RegExp> patterns,
) {
  final root = Directory(packageDir).resolveSymbolicLinksSync();
  final path = File(p.join(root, file)).resolveSymbolicLinksSync();
  String relative(String path) =>
      p.posix.joinAll(p.split(p.relative(path, from: root)));
  String? read(String path) {
    try {
      return utf8.decode(File(path).readAsBytesSync(), allowMalformed: true);
    } on FileSystemException {
      return null;
    }
  }

  final text = read(path)!;
  final main = _main.firstMatch(text);
  final hard = [
    if (_annotation.hasMatch(text)) 'file-annotation in $file',
    if (main == null)
      'no-main in $file'
    else ...[
      if (main.group(2)!.trim().isNotEmpty) 'main-with-args in $file',
      if (main.group(3) != null || (main.group(1) ?? '').startsWith('Future'))
        'async-main in $file',
    ],
  ];
  for (var dir = p.dirname(path);; dir = p.dirname(dir)) {
    final config = p.join(dir, 'flutter_test_config.dart');
    if (File(config).existsSync()) {
      hard.add('flutter-test-config in ${relative(config)}');
    }
    if (dir == root || !p.isWithin(root, dir)) break;
  }

  final soft = <String, String>{};
  final seen = {path};
  final stack = [path];
  while (stack.isNotEmpty) {
    final current = stack.removeLast();
    final helper = read(current);
    if (helper == null) continue;
    for (final regex in patterns) {
      if (regex.hasMatch(helper)) {
        soft.putIfAbsent(
            'isolation-pattern /${regex.pattern}/', () => relative(current));
      }
    }
    for (final match in _import.allMatches(helper)) {
      final uri = match.group(1)!;
      if (uri.contains(':')) continue;
      try {
        final target =
            File(p.join(p.dirname(current), uri)).resolveSymbolicLinksSync();
        if (p.isWithin(root, target) && seen.add(target)) stack.add(target);
      } on FileSystemException {
        continue;
      }
    }
  }
  return (
    hard: hard,
    soft: [for (final e in soft.entries) '${e.key} in ${e.value}'],
  );
}
